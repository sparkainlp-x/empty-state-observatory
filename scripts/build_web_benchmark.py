#!/usr/bin/env python3
"""Build the checked-in JSON and self-contained browser module from one benchmark."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from empty_state_observatory.monitor import run_benchmark  # noqa: E402


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--trials", type=int, default=200)
    parser.add_argument("--steps", type=int, default=160)
    args = parser.parse_args()
    report = run_benchmark(trials=args.trials, steps=args.steps)
    json_text = json.dumps(report, indent=2, sort_keys=True) + "\n"
    (ROOT / "web" / "benchmark.json").write_text(json_text, encoding="utf-8")
    js_text = "// Generated by scripts/build_web_benchmark.py; synthetic results only.\n"
    js_text += "export const BENCHMARK = Object.freeze(" + json.dumps(report, indent=2, sort_keys=True) + ");\n"
    (ROOT / "web" / "benchmark-data.js").write_text(js_text, encoding="utf-8")
    print(f"Wrote synthetic report for {args.trials} trials × {args.steps} steps to web/benchmark.json and web/benchmark-data.js")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
